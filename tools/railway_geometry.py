"""Exact, offline railway geometry. Coordinates are in a 256px Cell.

SVGs embed the reviewed sleeper material; rail.png is a palette/style reference,
never a stretched rail. Every port has two perpendicular, butt-ended steel rails.
"""
import base64
from io import BytesIO
import math
import struct
from urllib.parse import quote

SIZE = 256
GAUGE = 64  # distance between steel rail centers
RAIL_WIDTH = 8
SLEEPER_WIDTH = 96
SLEEPER_SPACING = 32
RADIUS = SIZE / 2
PORTS = (RADIUS - GAUGE / 2, RADIUS + GAUGE / 2)
SHAPES = {"straight": (0, 2), "curve": (0, 1), "tee": (0, 1, 2), "cross": (0, 1, 2, 3)}


def geometry(shape):
    """Return exact SVG rail paths and sleeper center/angle tuples."""
    paths, sleepers = [], []
    if shape in ("straight", "tee", "cross"):
        paths += [f"M {x:g} 0 V {SIZE}" for x in PORTS]
        sleepers += [(RADIUS, y, 0) for y in range(SLEEPER_SPACING//2, SIZE, SLEEPER_SPACING)]
    if shape == "cross":
        paths += [f"M 0 {y:g} H {SIZE}" for y in PORTS]
        sleepers += [(x, RADIUS, 90) for x in range(SLEEPER_SPACING//2, SIZE, SLEEPER_SPACING)]
    if shape in ("curve", "tee"):
        for r in PORTS:
            paths.append(f"M {SIZE-r:g} 0 A {r:g} {r:g} 0 0 0 {SIZE} {r:g}")
            if shape == "tee":
                paths.append(f"M {SIZE} {SIZE-r:g} A {r:g} {r:g} 0 0 0 {SIZE-r:g} {SIZE}")
        count = round(math.pi * RADIUS / 2 / SLEEPER_SPACING)
        for i in range(count):
            t = (i + .5) / count * math.pi / 2
            sleepers.append((SIZE-RADIUS*math.cos(t), RADIUS*math.sin(t), -math.degrees(t)))
            if shape == "tee":
                sleepers.append((SIZE-RADIUS*math.cos(t), SIZE-RADIUS*math.sin(t), math.degrees(t)))
    return paths, sleepers


def export_tracks(source, output):
    from PIL import Image, ImageCms, ImageOps
    with Image.open(source / "railway/sleeper.png") as original:
        original.load()
        image = ImageOps.exif_transpose(original).convert("RGBA")
        if original.info.get("icc_profile"):
            image = ImageCms.profileToProfile(image, ImageCms.ImageCmsProfile(BytesIO(original.info["icc_profile"])),
                                             ImageCms.createProfile("sRGB"), outputMode="RGBA")
        # Trim only fully transparent margins; retain all nonzero source alpha.
        image = image.crop(image.getchannel("A").getbbox())
        height = SLEEPER_WIDTH * image.height / image.width
        image.thumbnail((384, 384), Image.Resampling.LANCZOS)
        buffer = BytesIO()
        profile = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes())
        # LittleCMS otherwise inserts today's creation time into identical SVGs.
        profile[24:36] = struct.pack(">6H", 2000, 1, 1, 0, 0, 0)
        image.save(buffer, "PNG", icc_profile=bytes(profile))
        sleeper = base64.b64encode(buffer.getvalue()).decode("ascii")
    output.mkdir(parents=True, exist_ok=True)
    fallbacks = []
    for shape in SHAPES:
        paths, sleepers = geometry(shape)
        parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">',
                 f'<defs><image id="tie" x="{-SLEEPER_WIDTH/2:g}" y="{-height/2:g}" width="{SLEEPER_WIDTH}" height="{height:g}" href="data:image/png;base64,{sleeper}"/></defs>']
        parts += [f'<use href="#tie" transform="translate({x:.6f} {y:.6f}) rotate({angle:.6f})"/>' for x, y, angle in sleepers]
        # Draw all dark beds first, then steel and the slim polished running face.
        for width, color in ((RAIL_WIDTH, "#303231"), (5, "#777a75"), (2, "#c4c4b8")):
            parts += [f'<path d="{path}" fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="butt"/>' for path in paths]
        parts.append('</svg>')
        (output / f"{shape}.svg").write_text("\n".join(parts) + "\n", encoding="utf-8")
        fallback = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">' + ''.join(
            f'<path d="{path}" fill="none" stroke="#777a75" stroke-width="{RAIL_WIDTH}"/>' for path in paths) + '</svg>'
        fallbacks.append(f'#board[data-view="enhanced"] .cell[data-rail-shape="{shape}"] {{ --rail-fallback: url("data:image/svg+xml,{quote(fallback)}"); }}')
    (output / "fallbacks.css").write_text('/* Generated by tools/prepare-artwork.py; same exact steel paths as artwork. */\n' + '\n'.join(fallbacks) + '\n', encoding="utf-8")


def preview_tracks(source, output, preview):
    """Raster composition proof from the same path/sleeper coordinates (not browser QA)."""
    from PIL import Image, ImageDraw
    with Image.open(source / "railway/sleeper.png") as original:
        tie = original.convert("RGBA")
        tie = tie.crop(tie.getchannel("A").getbbox())
        tie = tie.resize((SLEEPER_WIDTH, round(SLEEPER_WIDTH * tie.height / tie.width)), Image.Resampling.LANCZOS)
    tiles = {}
    for shape in SHAPES:
        tile = Image.new("RGBA", (SIZE, SIZE))
        paths, sleepers = geometry(shape)
        for x, y, angle in sleepers:
            stamp = tie.rotate(-angle, resample=Image.Resampling.BICUBIC, expand=True)
            tile.alpha_composite(stamp, (round(x-stamp.width/2), round(y-stamp.height/2)))
        draw = ImageDraw.Draw(tile)
        for width, color in ((RAIL_WIDTH, "#303231"), (5, "#777a75"), (2, "#c4c4b8")):
            for path in paths:
                words = path.split()
                x, y = float(words[1]), float(words[2])
                if words[3] == "V": points = [(x, y), (x, 256)]
                elif words[3] == "H": points = [(x, y), (256, y)]
                else:
                    r = float(words[4])
                    points = [(256-r*math.cos(i*math.pi/128), r*math.sin(i*math.pi/128)) if y == 0
                              else (256-r*math.sin(i*math.pi/128), 256-r*math.cos(i*math.pi/128)) for i in range(65)]
                draw.line(points, fill=color, width=width, joint="curve")
        tiles[shape] = tile
    sheet = Image.new("RGB", (1000, 760), "#303a42")
    draw = ImageDraw.Draw(sheet)
    draw.text((16, 12), "Railway geometry | 256px reference / 60px Cells | material + independent outgoing arrows", fill="white")
    for row, shape in enumerate(SHAPES):
        draw.text((16, 50+row*76), shape, fill="white")
        for turn in range(4):
            base = Image.open(output / f"terrain/gravel/{(row+turn)%3+1:02}.webp").convert("RGBA")
            base.alpha_composite(tiles[shape].rotate(-turn*90))
            sheet.paste(base.resize((60, 60), Image.Resampling.LANCZOS), (110+turn*70, 40+row*76))
    # Connected 5x5 network includes curves, straight runs, T's and a cross.
    occupied = {(x,y) for x in range(5) for y in range(5) if x%2 == 0 or y%2 == 0}
    offsets = [(0,-1),(1,0),(0,1),(-1,0)]
    network = Image.new("RGB", (1280, 1280))
    for y in range(5):
        for x in range(5):
            base = Image.open(output / f"terrain/gravel/{(x+y)%3+1:02}.webp").convert("RGBA").rotate((x-y)*90)
            if (x,y) in occupied:
                sides = sorted(side for side,(dx,dy) in enumerate(offsets) if (x+dx,y+dy) in occupied)
                shape, turn = next((shape, turn) for shape, ports in SHAPES.items() for turn in range(4)
                                   if sorted((p+turn)%4 for p in ports) == sides)
                base.alpha_composite(tiles[shape].rotate(-turn*90))
                # Explicit sample outgoing direction, never baked into an export.
                arrow = Image.new("RGBA", (256,256))
                ImageDraw.Draw(arrow).polygon([(128,96),(148,120),(136,120),(136,160),(120,160),(120,120),(108,120)], fill="#f3deaa")
                base.alpha_composite(arrow.rotate(-sides[0]*90))
            network.paste(base, (x*256,y*256))
    sheet.paste(network.resize((600,600),Image.Resampling.LANCZOS),(390,50))
    sheet.paste(network.resize((300,300),Image.Resampling.LANCZOS),(40,390))
    sheet.save(preview, optimize=True)
